// Единая схема гайда для раздела PATH.
//
// Сиды в public/data/ исторически имеют каждый свою форму: у визы Казахстана
// секции — это именованные ключи верхнего уровня (channel_ru, docs_specifics_ru),
// у Украины — другие, у переезда — третьи. Компоненты «Маршрута» не должны об
// этом знать, поэтому между сидом и страницей стоит адаптер, который приводит
// конкретный сид к типам ниже. Сами JSON при этом не переписываются.

/**
 * Насколько можно доверять секции без похода на официальный сайт.
 *
 * `verify` ставится, если в исходном тексте был маркер [TTL] (протухает со
 * временем) или [УТОЧНИТЬ] (мы сами не уверены), либо если текст прямо говорит
 * о нестабильности. Разница между двумя маркерами сохраняется в ttlNote.
 */
export type Confidence = 'confirmed' | 'verify';

/**
 * Блоки, из которых собирается тело станции.
 *
 * У карточки абзацы и список лежат вместе, а не двумя блоками: в макете это
 * одна поверхность, и разложить их по двум карточкам — значит порвать её
 * пополам белой полосой.
 */
export type GuideBlock =
  | { kind: 'card'; paragraphs?: string[]; items?: string[] }
  | { kind: 'band'; label: string; paragraphs: string[]; link?: { href: string; label: string } };

export interface GuideSection {
  id: string;
  /** Порядковый номер станции, с единицы. Рисуется как 01, 02, … */
  index: number;
  /** Русский заголовок станции. */
  title: string;
  /**
   * Итальянский термин, которым эту вещь называют в бюрократии.
   * Пустая строка — законное значение: выдумывать термин нельзя,
   * компонент отрабатывает отсутствие глоссы (см. MIGRATION-TODO.md).
   */
  gloss: string;
  confidence: Confidence;
  /** Строка под блоком: что именно и почему стоит перепроверить. */
  ttlNote?: string;
  body: GuideBlock[];
}

export interface Guide {
  /** «Казахстан · 2026–2027» — надстрочник над заголовком. */
  eyebrow: string;
  /** «Виза D» — h1. */
  title: string;
  /** «Visto nazionale · studio» — итальянский подзаголовок. */
  gloss: string;
  /** Лид-абзац под золотой линией. Пустая строка — законное значение. */
  lead: string;
  sections: GuideSection[];
  /** Курсивная строка в конце маршрута: куда человек идёт дальше. */
  outro?: string;
}

/** Термины, которые подсвечиваются в тексте станции. */
export const TERM_PATTERN =
  /(Universitaly|Prenot@Mi|permesso di soggiorno|codice fiscale|visto nazionale|nulla osta|Kaspi|CIMEA|DDV)/gi;
