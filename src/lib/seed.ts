// Кэш-бастинг сидов. Сиды в /data/*.json не хэшируются Vite (лежат в public/),
// поэтому Cloudflare/браузер могли отдавать устаревшую версию после деплоя —
// страницы «путались»: новая вёрстка со старыми данными и наоборот. Добавляем
// к URL метку сборки: каждый деплой = новый URL = гарантированный cache miss.

export function seedUrl(path: string): string {
  return `${path}?v=${__BUILD_ID__}`;
}
